// ── Lang helpers ──────────────────────────────────────────────────
window.KG_LANGS = ['es', 'en'];

window.kgDetectLang = function() {
  const saved = localStorage.getItem('keygo-lang');
  if (saved && window.KG_LANGS.includes(saved)) return saved;
  const b = (navigator.language || 'en').slice(0, 2).toLowerCase();
  return window.KG_LANGS.includes(b) ? b : 'en';
};

window.kgSetLang = function(l) {
  localStorage.setItem('keygo-lang', l);
  document.documentElement.lang = l;
};

window.kgT = function(lang, key) {
  return (window.KG_I18N[lang] && window.KG_I18N[lang][key])
    || (window.KG_I18N['en'] && window.KG_I18N['en'][key])
    || key;
};
